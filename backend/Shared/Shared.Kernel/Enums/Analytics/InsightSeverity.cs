namespace Qwestr.Shared.Kernel.Enums.Analytics;

/// <summary>
/// Степень важности инсайта, сгенерированного на основе аналитических данных.
/// Используется для визуального выделения в UI и приоритизации внимания HR-менеджера.
/// </summary>
public enum InsightSeverity
{
    /// <summary>
    /// Положительное наблюдение или нейтральная справка.
    /// </summary>
    Info = 0,

    /// <summary>
    /// Отклонение метрики от ожидаемого значения на 20–50%.
    /// Требует внимания, но не критично.
    /// </summary>
    Warning = 1,

    /// <summary>
    /// Метрика хуже ожидаемой более чем на 50% либо выявлена системная проблема.
    /// Требует немедленного действия со стороны HR.
    /// </summary>
    Critical = 2
}