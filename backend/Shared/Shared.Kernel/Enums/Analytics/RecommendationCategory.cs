namespace Qwestr.Shared.Kernel.Enums.Analytics;

/// <summary>
/// Категория рекомендации, сгенерированной на основе анализа метрик.
/// Помогает HR-менеджеру понять, в какую область стоит направить усилия.
/// </summary>
public enum RecommendationCategory
{
    /// <summary>
    /// Качество контента онбординга: формулировки вопросов, структура шагов,
    /// порядок материалов в сценарии.
    /// </summary>
    Content = 0,

    /// <summary>
    /// Процесс адаптации: длительность этапов, регулярность обратной связи,
    /// порядок назначения сценариев.
    /// </summary>
    Process = 1,

    /// <summary>
    /// Мотивация и вовлечённость: настройка системы баллов, бейджей,
    /// взаимодействие наставника с новичком.
    /// </summary>
    Motivation = 2
}