namespace Qwestr.Shared.Kernel.Enums.Analytics;

/// <summary>
/// Источник генерации набора инсайтов.
/// Различает автоматический прогрев кеша и ручной запрос менеджера.
/// </summary>
public enum InsightTrigger
{
    /// <summary>
    /// Сгенерировано фоновым джобом по расписанию (раз в сутки).
    /// Обеспечивает мгновенный показ инсайтов при открытии дашборда.
    /// </summary>
    Scheduled = 0,

    /// <summary>
    /// Сгенерировано по нажатию кнопки в UI.
    /// Учитывается в cooldown-логике (раз в 5 часов на тенант).
    /// </summary>
    Manual = 1
}